package com.dima.fooddelivery.review.domain;

/**
 * Оценка отдельного блюда внутри отзыва.
 *
 * <p>Отдельной коллекции у этого типа нет: он лежит вложенным массивом в документе отзыва.
 * В этом и смысл документной модели — данные, которые всегда читаются вместе, и хранятся
 * вместе. В реляционной схеме здесь была бы таблица {@code review_dish_rating} с внешним
 * ключом и join'ом на каждое чтение списка отзывов.
 *
 * <p>{@code menuItemName} скопировано на момент отзыва по той же причине, по которой оно
 * скопировано в позицию заказа: блюдо потом переименуют, а отзыв обязан остаться понятным.
 */
public record DishRating(
        Long menuItemId,
        String menuItemName,
        int rating
) {
}
