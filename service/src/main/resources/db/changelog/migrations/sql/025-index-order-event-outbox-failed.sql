-- Индекс под метрику «сколько событий застряло».
--
-- Очередь на публикацию наблюдается двумя числами: PENDING (сколько ещё не ушло)
-- и FAILED (сколько не уйдёт уже никогда без вмешательства человека). Первое считается
-- по частичному индексу из миграции 024, второе до сих пор считалось перебором всей
-- таблицы — а Prometheus опрашивает метрики раз в несколько секунд, и таблица outbox
-- растёт неограниченно.
--
-- Индекс тоже частичный: FAILED-записей должны быть единицы, и индекс на них остаётся
-- крошечным, а подсчёт превращается в чтение одного индекса вместо всей таблицы.
CREATE INDEX IF NOT EXISTS idx_order_event_outbox_failed
    ON ${appSchema}.order_event_outbox (id)
    WHERE status = 'FAILED';
