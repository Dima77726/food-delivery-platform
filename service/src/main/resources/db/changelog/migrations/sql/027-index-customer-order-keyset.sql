-- Индексы под курсорную выборку заказов.
--
-- Курсор ищет строки по условию (created_at, id) < (?, ?) и отдаёт их в порядке
-- ORDER BY created_at DESC, id DESC. Без индекса, в котором эти колонки идут в том же
-- порядке и в ту же сторону, PostgreSQL прочитает все заказы владельца, отсортирует их
-- целиком и выбросит всё, кроме двадцати строк, — то есть ровно та работа, ради ухода
-- от которой курсор и вводился.
--
-- Ведущая колонка — владелец списка: выборка всегда ограничена одним клиентом или одним
-- рестораном, и без него индекс пришлось бы обходить по всей таблице.
--
-- Существующие idx_customer_order_customer_id и idx_customer_order_restaurant_id
-- становятся префиксами этих индексов и потому избыточны. Здесь они не удаляются
-- намеренно: снос индексов стоит делать отдельным шагом, наблюдая за планами запросов,
-- а не заодно с добавлением новых.
--
-- Индекса под фильтр по статусу нет сознательно: заказов у ресторана в одном статусе
-- заметная доля от общего числа, и отсеивание их при обходе упорядоченного индекса
-- дешевле, чем четвёртая колонка в ключе и ещё одно дерево на запись.

CREATE INDEX IF NOT EXISTS idx_customer_order_customer_created_at_id
    ON ${appSchema}.customer_order (customer_id, created_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_customer_order_restaurant_created_at_id
    ON ${appSchema}.customer_order (restaurant_id, created_at DESC, id DESC);
