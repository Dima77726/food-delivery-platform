package com.dima.fooddelivery.contracts.order;

/**
 * Топики, через которые сервис заказов говорит с остальными.
 *
 * <p>Имя топика — такая же часть контракта, как и форма сообщения: переименуй его
 * у продюсера, не предупредив потребителей, и они молча перестанут что-либо получать.
 * Поэтому оно живёт здесь, рядом с {@link OrderIntegrationEvent}, а не в коде одного
 * из сервисов.
 *
 * <p>Топиков разбора (DLT) здесь нет намеренно. DLT принадлежит потребителю, а не продюсеру:
 * у каждого сервиса свои отказы, свой разбор и свой алерт, и делить один топик ошибок
 * на всех означало бы искать чужие сбои среди своих.
 */
public final class OrderEventTopics {

    /** События жизненного цикла заказа. Ключ сообщения — идентификатор заказа. */
    public static final String ORDER_EVENTS = "food-delivery.order-events";

    /**
     * Заголовок со сквозной меткой запроса. Едет рядом с телом, а не внутри него:
     * метка — не часть события, а след того, кто его вызвал.
     */
    public static final String CORRELATION_ID_HEADER = "X-Correlation-Id";

    private OrderEventTopics() {
    }
}
